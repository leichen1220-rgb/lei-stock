const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const html=fs.readFileSync(path.join(__dirname,'../index.html'),'utf8');
const source=html.slice(html.indexOf('function orderedTransactions(items){'),html.indexOf('function renderOverview(){'));
const calculate=new Function('trades',source+';return excelCostLedger()');
const buy={ticker:'TEST',trade_date:'2026-01-01',transaction_type:'現股',quantity:100,price:20,trade_fees:5,paid_cost:2005};
const sell={...buy,trade_date:'2026-01-02',quantity:-40,price:25,trade_fees:3,paid_cost:null};
const div={ticker:'TEST',trade_date:'2026-01-03',transaction_type:'現金股息',dividend_gross:100,wire_fee:5,payment_confirmed:true};
const run=rows=>calculate(rows).states.get('TEST');
let st=run([buy,sell,div]);assert.equal(st.quantity,60);assert.equal(st.cost,913);assert.equal(st.valid,true);
st=run([{...buy,paid_cost:1905}]);assert.equal(st.cost,1905);
