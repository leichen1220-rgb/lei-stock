st=run([buy,{...div,wire_fee:null,payment_confirmed:false}]);assert.equal(st.cost,1905);assert.equal(st.pendingDividends,1);
st=run([buy,{...div,wire_fee:0,payment_confirmed:false}]);assert.equal(st.pendingDividends,0);
st=run([{...buy,paid_cost:null,trade_fees:null}]);assert.equal(st.valid,false);
st=run([{...buy,paid_cost:0}]);assert.equal(st.cost,0);assert.equal(st.valid,true);
st=run([buy,{...sell,quantity:-101}]);assert.equal(st.valid,false);
st=run([div,sell,buy]);assert.equal(st.cost,913);
st=run([buy,{...sell,paid_cost:200}]);assert.equal(st.cost,1008);
assert.ok(html.includes('excelCostBody'));assert.ok(!html.includes("['成本／損益','待核對']"));assert.ok(html.includes('obj.paid_cost=null'));
